//! Generates both sides of a kernel library's launcher ABI.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use crate::extent::{Expr, Relation};
use crate::manifest::{Elem, Kind, Launcher, Manifest, Param, Returns, Scalar};

/// The parameter's type in the C++ launcher signature; `f16` buffers use
/// the library's `f16_type` (default `void`).
fn cpp_param_type(p: &Param, format_type: &str, f16_type: &str) -> String {
    let list = p.list.is_some();
    let elem = |e: Elem| if e == Elem::F16 { f16_type } else { e.cpp() };
    let index = if p.signed {
        "std::int32_t"
    } else {
        "std::uint32_t"
    };
    match (p.kind, p.elem, p.scalar) {
        // Lists are host arrays, of device pointers for buffers.
        (Kind::Scalar, _, Some(s)) if list => format!("const {}*", s.cpp()),
        (Kind::In, Some(e), _) if list => format!("const {}* const*", elem(e)),
        (Kind::Inout | Kind::Out, Some(e), _) if list => format!("{}* const*", elem(e)),
        (Kind::Scalar, _, Some(s)) => s.cpp().into(),
        (Kind::Indices, _, _) => format!("const {index}*"),
        (Kind::IndicesOut, _, _) => format!("{index}*"),
        (Kind::Quant, _, _) => "const void*".into(),
        (Kind::Format, _, _) => format_type.into(),
        (Kind::Const | Kind::Table, _, _) => p.cpp_type.clone().unwrap_or_default(),
        (Kind::Stream, _, _) => "hipStream_t".into(),
        (Kind::Alias, Some(e), _) if p.read_only => format!("const {}*", elem(e)),
        (Kind::Alias, Some(e), _) => format!("{}*", elem(e)),
        (Kind::In, Some(e), _) => format!("const {}*", elem(e)),
        (_, Some(e), _) => format!("{}*", elem(e)),
        _ => unreachable!("validated manifest"),
    }
}

/// The parameter's type across `extern "C"` (formats travel as their ID).
fn rust_ffi_type(p: &Param) -> String {
    let list = p.list.is_some();
    match (p.kind, p.elem, p.scalar) {
        (Kind::Scalar, _, Some(s)) if list => format!("*const {}", s.rust()),
        (Kind::In, Some(e), _) if list => format!("*const *const {}", e.rust()),
        (Kind::Inout | Kind::Out, Some(e), _) if list => format!("*const *mut {}", e.rust()),
        (Kind::Scalar, _, Some(s)) => s.rust().into(),
        (Kind::Indices, _, _) if p.signed => "*const i32".into(),
        (Kind::IndicesOut, _, _) if p.signed => "*mut i32".into(),
        (Kind::Indices, _, _) => "*const u32".into(),
        (Kind::IndicesOut, _, _) => "*mut u32".into(),
        (Kind::Quant, _, _) => "*const u8".into(),
        (Kind::Format, _, _) => "u16".into(),
        (Kind::Table, _, _) => "*const ::std::ffi::c_void".into(),
        (Kind::Alias, Some(e), _) if p.read_only => format!("*const {}", e.rust()),
        (Kind::Alias, Some(e), _) => format!("*mut {}", e.rust()),
        (Kind::In, Some(e), _) => format!("*const {}", e.rust()),
        (_, Some(e), _) => format!("*mut {}", e.rust()),
        _ => unreachable!("validated manifest"),
    }
}

/// `extern "C"` shim: exact-signature check, exception barrier, launch status.
pub fn cpp_shim(m: &Manifest) -> String {
    let prefix = format!("gufo_{}_", m.library.name);
    let mut s = String::from(
        "// Generated by gufo-kernel-build from launch.toml. Do not edit.\n\
         #include <hip/hip_runtime.h>\n\n#include <cstddef>\n#include <cstdint>\n#include <type_traits>\n\n",
    );
    for header in &m.library.headers {
        let _ = writeln!(s, "#include \"{header}\"");
    }
    s.push_str(
        "\nextern \"C\" struct GufoLaunchResult {\n  std::int32_t status;\n  std::int32_t hip_error;\n};\n\n\
         namespace {\n\
         constexpr std::int32_t kOk = 0, kUnsupported = 1, kHipError = 2, kException = 3;\n\
         GufoLaunchResult Finish() noexcept {\n  const hipError_t e = hipGetLastError();\n  \
         return {e == hipSuccess ? kOk : kHipError, static_cast<std::int32_t>(e)};\n}\n\
         }  // namespace\n",
    );
    for l in &m.launchers {
        // `::`-prefixed names are fully qualified (launchers outside the
        // library namespace, such as the shared vision kernels).
        let qualified = if l.cpp.starts_with("::") {
            l.cpp.clone()
        } else {
            format!("{}::{}", m.library.namespace, l.cpp)
        };
        let format_type = m.library.format_type.as_deref().unwrap_or_default();
        let f16_type = m.library.f16_type.as_deref().unwrap_or("void");
        let passed: Vec<&Param> = l.params.iter().filter(|p| !p.contract_only).collect();
        let types: Vec<String> = passed
            .iter()
            .map(|p| cpp_param_type(p, format_type, f16_type))
            .collect();
        let explicit_stream = passed.iter().any(|p| p.kind == Kind::Stream);
        let signature = if explicit_stream {
            types.join(", ")
        } else {
            with_last(&types, "hipStream_t")
        };
        let ret = match l.returns {
            Returns::Void => "void",
            Returns::Supported => "bool",
        };
        // The cast selects the overload with exactly this signature and fails
        // to compile when none exists (default arguments do not count).
        let _ = write!(
            s,
            "\n// launch.toml `{}` must match the C++ signature of {} exactly.\n\
             static_assert(std::is_same_v<decltype(static_cast<{ret} (*)({signature})>(&{qualified})),\n    \
             {ret} (*)({signature})>);\n",
            l.name, l.cpp,
        );
        // A table's header is the `{ pointer, u32 count, i32 tag }` that
        // `gufo_hip::RowTable` writes.
        for p in passed.iter().filter(|p| p.kind == Kind::Table) {
            let _ = writeln!(
                s,
                "static_assert(sizeof(std::remove_pointer_t<{0}>) == 16 && alignof(std::remove_pointer_t<{0}>) == 8, \"launch.toml `{1}`: `{2}` must be a RowTable header\");",
                p.cpp_type.as_deref().unwrap_or_default(),
                l.name,
                p.name
            );
        }
        let params: Vec<String> = passed
            .iter()
            .zip(&types)
            .filter(|(p, _)| !matches!(p.kind, Kind::Const | Kind::Stream))
            .map(|(p, t)| {
                let t = if p.kind == Kind::Format {
                    "std::uint16_t"
                } else {
                    t.as_str()
                };
                format!("{t} {}", p.name)
            })
            .collect();
        let args: Vec<String> = passed
            .iter()
            .map(|p| match p.kind {
                Kind::Const => p.value.clone().unwrap_or_default(),
                Kind::Stream => "stream".into(),
                Kind::Format => format!("static_cast<{format_type}>({})", p.name),
                _ => p.name.clone(),
            })
            .collect();
        let call = if explicit_stream {
            format!("{qualified}({})", args.join(", "))
        } else {
            format!("{qualified}({})", with_last(&args, "stream"))
        };
        // Clear the thread's last error first: it may stem from an unrelated
        // earlier call (for example an ended capture), not from this launch.
        let body = match l.returns {
            Returns::Void => {
                format!("    (void)hipGetLastError();\n    {call};\n    return Finish();")
            }
            Returns::Supported => format!(
                "    (void)hipGetLastError();\n    if (!{call}) return {{kUnsupported, 0}};\n    return Finish();"
            ),
        };
        let _ = write!(
            s,
            "extern \"C\" GufoLaunchResult {prefix}{}({}) noexcept {{\n  try {{\n{body}\n  \
             }} catch (...) {{\n    return {{kException, 0}};\n  }}\n}}\n",
            l.name,
            with_last(&params, "hipStream_t stream")
        );
    }
    s
}

/// `items` and then `last`, comma-separated (only `last` for none).
fn with_last(items: &[String], last: &str) -> String {
    if items.is_empty() {
        last.to_string()
    } else {
        format!("{}, {last}", items.join(", "))
    }
}

/// `first` and then `items`, comma-separated (only `first` for none).
fn with_first(first: &str, items: &[String]) -> String {
    if items.is_empty() {
        first.to_string()
    } else {
        format!("{first}, {}", items.join(", "))
    }
}

/// Safe Rust wrappers plus their raw `extern "C"` declarations.
pub fn rust_bindings(m: &Manifest) -> String {
    let prefix = format!("gufo_{}_", m.library.name);
    let mut s = String::from(
        "// Generated by gufo-kernel-build from launch.toml. Do not edit.\n\nmod ffi {\n",
    );
    s.push_str("    unsafe extern \"C\" {\n");
    for l in &m.launchers {
        let params: Vec<String> = l
            .params
            .iter()
            .filter(|p| !p.contract_only && !matches!(p.kind, Kind::Const | Kind::Stream))
            .map(|p| format!("{}: {}", p.name, rust_ffi_type(p)))
            .collect();
        let _ = writeln!(
            s,
            "        pub fn {prefix}{}({}) -> ::gufo_hip::launch::RawLaunchResult;",
            l.name,
            with_last(&params, "stream: ::gufo_hip::sys::HipStream")
        );
    }
    s.push_str("    }\n}\n");
    for l in &m.launchers {
        s.push_str(&rust_wrapper(l, &prefix));
    }
    s.push_str(&probe_module(m));
    s
}

/// Extent probes: each launch gets buffers of exactly the declared extent
/// followed by a guard region; written buffers carry a byte pattern that must
/// survive. Catches extents that are too small for what a kernel writes (not
/// for what it reads).
fn probe_module(m: &Manifest) -> String {
    let mut s = String::from(
        "\n/// Extent probes generated from launch.toml; run by the crate's GPU tests.\n\
         #[doc(hidden)]\n\
         pub mod probes {\n    \
         const GUARD: usize = 4096;\n    \
         const PATTERN: u8 = 0xA5;\n\n    \
         fn guard_intact<T: ::gufo_hip::DeviceCopy>(\n        \
         stream: &::gufo_hip::Stream,\n        \
         buffer: &::gufo_hip::DeviceBuffer<T>,\n        \
         len: usize,\n    \
         ) -> Result<bool, ::gufo_hip::LaunchError> {\n        \
         let mut bytes = vec![0u8; GUARD * size_of::<T>()];\n        \
         stream.download_bytes(buffer.slice(len..len + GUARD), &mut bytes)?;\n        \
         Ok(bytes.iter().all(|&b| b == PATTERN))\n    \
         }\n\n    \
         #[allow(dead_code)]\n    \
         fn indices_guard_intact(\n        \
         stream: &::gufo_hip::Stream,\n        \
         buffer: &::gufo_hip::DeviceIndices,\n        \
         len: usize,\n        \
         value: u32,\n    \
         ) -> Result<bool, ::gufo_hip::LaunchError> {\n        \
         let mut values = vec![0u32; GUARD];\n        \
         stream.download(buffer.slice(len..len + GUARD).values(), &mut values)?;\n        \
         Ok(values.iter().all(|&v| v == value))\n    \
         }\n",
    );
    for l in &m.launchers {
        s.push_str(&probe_function(l));
    }
    let names: Vec<String> = m
        .launchers
        .iter()
        .map(|l| format!("        violations.extend({}(stream)?);", l.name))
        .collect();
    let _ = write!(
        s,
        "\n    /// Every probe of every launcher; returns the violations found.\n    \
         pub fn all(stream: &::gufo_hip::Stream) -> Result<Vec<String>, ::gufo_hip::LaunchError> {{\n        \
         let mut violations = Vec::new();\n{}\n        Ok(violations)\n    }}\n}}\n",
        names.join("\n")
    );
    s
}

fn probe_function(l: &Launcher) -> String {
    let probes = l.probes().unwrap_or_default();
    let name = &l.name;
    let mut s = String::new();
    let _ = writeln!(
        s,
        "\n    // Probes omit optional buffers, and simple extents need no helpers.\n    \
         #[allow(unused_imports, unused_variables, unused_mut)]\n    \
         pub fn {name}(stream: &::gufo_hip::Stream) -> Result<Vec<String>, ::gufo_hip::LaunchError> {{\n        \
         use ::gufo_hip::launch as l;\n        let mut violations = Vec::new();"
    );
    for (index, probe) in probes.iter().enumerate() {
        let present = |p: &crate::manifest::Param| !p.optional || probe.with.contains(&p.name);
        // Scalars first, then the conversions extents use, then the buffers.
        let mut scalars = String::new();
        let mut body = String::new();
        let mut args = Vec::new();
        let mut guarded = Vec::new();
        let mut indices_guarded = Vec::new();
        let mut derivations = String::new();
        let mut listed_guards = Vec::new();
        for p in &l.params {
            let n = &p.name;
            match (p.kind, p.elem, p.scalar) {
                (Kind::Scalar, _, Some(sc)) if p.list.is_some() => {
                    let _ = writeln!(
                        scalars,
                        "            let {n}: Vec<{}> = {};",
                        sc.rust(),
                        probe.literals[n]
                    );
                    args.push(format!("&{n}"));
                }
                (Kind::Scalar, _, Some(sc)) => {
                    let _ = writeln!(
                        scalars,
                        "            let {n}: {} = {};",
                        sc.rust(),
                        probe.literals[n]
                    );
                    args.push(n.clone());
                }
                (Kind::Indices | Kind::IndicesOut, _, _) => {
                    let expr = Expr::parse(p.len.as_deref().unwrap_or_default())
                        .map(|e| e.rust(n))
                        .unwrap_or_default();
                    let below = Expr::parse(p.below.as_deref().unwrap_or_default())
                        .map(|e| e.rust(n))
                        .unwrap_or_default();
                    // The largest valid index reaches the furthest access (unless
                    // the probe chooses a value); kernel-written indices must
                    // leave it in the guard.
                    let value = probe
                        .fills
                        .get(n)
                        .map_or(format!("below_{n} - 1"), |v| format!("{v}u32"));
                    let _ = writeln!(
                        body,
                        "            let len_{n} = {expr};\n            \
                         let below_{n} = u32::try_from({below}).map_err(|_| ::gufo_hip::LaunchError::InvalidArgument {{ param: \"{n}\", reason: \"probe bound exceeds u32\" }})?;\n            \
                         let spec_{n} = ::gufo_hip::IndexSpec {{ bound: below_{n}, mask: {}, padded: {}, signed: {} }};\n            \
                         let mut buffer_{n} = stream.alloc_indices_with(len_{n} + GUARD, spec_{n})?;\n            \
                         stream.upload_indices(&vec![{value}; len_{n} + GUARD], &mut buffer_{n})?;",
                        mask_literal(p),
                        p.padded,
                        p.signed
                    );
                    if p.kind == Kind::IndicesOut {
                        args.push(format!("buffer_{n}.slice_mut(0..len_{n})"));
                        indices_guarded.push(n.clone());
                    } else {
                        args.push(format!("buffer_{n}.slice(0..len_{n})"));
                        if let Some(source) = &p.derived_from {
                            let _ = writeln!(
                                derivations,
                                "            // SAFETY: probe values of derived indices are chosen in\n            \
                                 // launch.toml to keep every access in its extent, which\n            \
                                 // the guards verify.\n            \
                                 unsafe {{ buffer_{n}.assume_derived(0..len_{n}, buffer_{source}.slice(0..len_{source}).derivation({} as u64)) }};",
                                tag_expr(p)
                            );
                        }
                    }
                }
                (Kind::Quant, _, _) => {
                    let expr = |text: &Option<String>| {
                        Expr::parse(text.as_deref().unwrap_or_default())
                            .map(|e| e.rust(n))
                            .unwrap_or_default()
                    };
                    let format = &probe.literals[n];
                    let _ = writeln!(
                        body,
                        "            let format_{n} = ::gufo_hip::GgmlType::from_name(\"{format}\").ok_or(::gufo_hip::LaunchError::InvalidArgument {{ param: \"{n}\", reason: \"unknown probe format\" }})?;\n            \
                         let len_{n} = l::add(l::mul({}, usize::try_from(format_{n}.encoded_bytes({} as u64).unwrap_or(0)).unwrap_or(usize::MAX), \"{n}\")?, {}, \"{n}\")?;\n            \
                         let mut buffer_{n} = stream.alloc::<u8>(len_{n} + GUARD)?;\n            \
                         stream.fill_bytes(buffer_{n}.as_mut_slice(), 0)?;",
                        expr(&p.rows),
                        expr(&p.cols),
                        if p.tail.is_some() {
                            expr(&p.tail)
                        } else {
                            "0usize".into()
                        },
                    );
                    args.push(format!(
                        "::gufo_hip::QuantSlice::new(buffer_{n}.slice(0..len_{n}), format_{n})"
                    ));
                }
                (Kind::Format | Kind::Const | Kind::Alias | Kind::Stream, _, _) => {}
                (kind, Some(e), _) if p.list.is_some() => {
                    let count = l.list_count().unwrap_or_default();
                    let input = kind == Kind::In;
                    let (slice, iter, view) = if input {
                        ("&", "iter", "slice")
                    } else {
                        ("&mut ", "iter_mut", "slice_mut")
                    };
                    if !present(p) {
                        args.push(format!(
                            "{slice}(0..x_{count}).map(|_| None).collect::<Vec<_>>()"
                        ));
                        continue;
                    }
                    let expr = Expr::parse(p.len.as_deref().unwrap_or_default())
                        .map(|e| e.rust(n))
                        .unwrap_or_default();
                    let fill = if input { "0" } else { "PATTERN" };
                    let upload = probe
                        .fills
                        .get(n)
                        .map(|value| {
                            format!(
                                "                stream.upload(&vec![{value}u32; len], buffer.slice_mut(0..len))?;\n"
                            )
                        })
                        .unwrap_or_default();
                    let _ = write!(
                        body,
                        "            let mut buffer_{n} = Vec::new();\n            \
                         let mut len_{n} = Vec::new();\n            \
                         #[allow(clippy::needless_range_loop)] // list scalars share `i`\n            \
                         for i in 0..x_{count} {{\n{}                \
                         let len = {expr};\n                \
                         let mut buffer = stream.alloc::<{}>(len + GUARD)?;\n                \
                         stream.fill_bytes(buffer.as_mut_slice(), {fill})?;\n{upload}                \
                         buffer_{n}.push(buffer);\n                \
                         len_{n}.push(len);\n            }}\n",
                        element_conversions(l, "                "),
                        e.rust()
                    );
                    let wrap = if p.optional {
                        format!("Some(b.{view}(0..len))")
                    } else {
                        format!("b.{view}(0..len)")
                    };
                    args.push(format!(
                        "{slice}buffer_{n}.{iter}().zip(&len_{n}).map(|(b, &len)| {wrap}).collect::<Vec<_>>()"
                    ));
                    if !input {
                        listed_guards.push(n.clone());
                    }
                }
                (kind, Some(e), _) if present(p) => {
                    let expr = Expr::parse(p.len.as_deref().unwrap_or_default())
                        .map(|e| e.rust(n))
                        .unwrap_or_default();
                    let fill = if kind == Kind::In { "0" } else { "PATTERN" };
                    // Managed memory is host-visible at the device address.
                    let alloc = if p.host_visible {
                        "alloc_managed"
                    } else {
                        "alloc"
                    };
                    let _ = writeln!(
                        body,
                        "            let len_{n} = {expr};\n            \
                         let mut buffer_{n} = stream.{alloc}::<{}>(len_{n} + GUARD)?;\n            \
                         stream.fill_bytes(buffer_{n}.as_mut_slice(), {fill})?;",
                        e.rust()
                    );
                    if let Some(value) = probe.fills.get(n) {
                        let _ = writeln!(
                            body,
                            "            stream.upload(&vec![{value}u32; len_{n}], buffer_{n}.slice_mut(0..len_{n}))?;"
                        );
                    }
                    let view = if kind == Kind::In {
                        format!("buffer_{n}.slice(0..len_{n})")
                    } else {
                        guarded.push(n.clone());
                        format!("buffer_{n}.slice_mut(0..len_{n})")
                    };
                    args.push(if p.optional {
                        format!("Some({view})")
                    } else {
                        view
                    });
                }
                _ => args.push("None".into()),
            }
        }
        let call = format!("super::{name}({})?", with_first("stream", &args));
        let launch = match l.returns {
            Returns::Void => format!("            {call};\n"),
            Returns::Supported => format!(
                "            if {call} == ::gufo_hip::Launch::Unsupported {{\n                \
                 violations.push(\"{name} probe {index}: the launcher declined the probe geometry\".to_string());\n            }}\n"
            ),
        };
        let mut checks: String = guarded
            .iter()
            .map(|n| {
                format!(
                    "            if !guard_intact(stream, &buffer_{n}, len_{n})? {{\n                \
                     violations.push(\"{name} probe {index}: `{n}` was written beyond its declared extent\".to_string());\n            }}\n"
                )
            })
            .collect();
        for n in &indices_guarded {
            let _ = write!(
                checks,
                "            if !indices_guard_intact(stream, &buffer_{n}, len_{n}, below_{n} - 1)? {{\n                \
                 violations.push(\"{name} probe {index}: `{n}` was written beyond its declared extent\".to_string());\n            }}\n"
            );
        }
        for n in &listed_guards {
            let _ = write!(
                checks,
                "            for (element, (buffer, &len)) in buffer_{n}.iter().zip(&len_{n}).enumerate() {{\n                \
                 if !guard_intact(stream, buffer, len)? {{\n                    \
                 violations.push(format!(\"{name} probe {index}: `{n}[{{element}}]` was written beyond its declared extent\"));\n                \
                 }}\n            }}\n"
            );
        }
        let _ = write!(
            s,
            "        {{\n{scalars}{}{body}{derivations}{launch}            stream.synchronize()?;\n{checks}        }}\n",
            extent_conversions(l, "            ")
        );
    }
    s.push_str("        Ok(violations)\n    }\n");
    s
}

/// `let x_<name>: usize` of element `i` for every list scalar.
fn element_conversions(l: &Launcher, indent: &str) -> String {
    let mut s = String::new();
    for p in l
        .params
        .iter()
        .filter(|p| p.kind == Kind::Scalar && p.list.is_some())
    {
        let n = &p.name;
        if p.scalar == Some(Scalar::Usize) {
            let _ = writeln!(s, "{indent}let x_{n} = {n}[i];");
        } else {
            let _ = writeln!(
                s,
                "{indent}let x_{n} = usize::try_from({n}[i])\n{indent}    \
                 .map_err(|_| ::gufo_hip::LaunchError::ExtentOverflow {{ param: \"{n}\" }})?;"
            );
        }
    }
    s
}

/// Whether a requirement holds per list element.
fn per_element(l: &Launcher, relation: &Relation) -> bool {
    let lists = l.list_scalars();
    relation
        .idents()
        .iter()
        .any(|name| lists.contains(name.as_str()))
}

/// `let x_<name>: usize` for every integer scalar an extent, index bound or
/// requirement uses.
fn extent_conversions(l: &Launcher, indent: &str) -> String {
    let mut used: BTreeSet<String> = l
        .params
        .iter()
        .flat_map(|p| {
            [
                p.len.as_deref(),
                p.below.as_deref(),
                p.rows.as_deref(),
                p.cols.as_deref(),
                p.tag.as_deref(),
            ]
        })
        .flatten()
        .flat_map(|text| Expr::parse(text).map(|e| e.idents()).unwrap_or_default())
        .collect();
    used.extend(
        l.requires
            .iter()
            .flat_map(|r| Relation::parse(r).map(|r| r.idents()).unwrap_or_default()),
    );
    used.extend(l.list_count().map(String::from));
    let mut s = String::new();
    for p in l
        .params
        .iter()
        .filter(|p| used.contains(&p.name) && p.list.is_none())
    {
        let n = &p.name;
        if p.scalar == Some(Scalar::Usize) {
            let _ = writeln!(s, "{indent}let x_{n} = {n};");
        } else {
            let _ = writeln!(
                s,
                "{indent}let x_{n} = usize::try_from({n})\n{indent}    \
                 .map_err(|_| ::gufo_hip::LaunchError::ExtentOverflow {{ param: \"{n}\" }})?;"
            );
        }
    }
    s
}

/// The Rust literal of an index parameter's mask (all bits by default).
fn mask_literal(p: &Param) -> String {
    format!("{}u32", p.mask.unwrap_or(u32::MAX))
}

/// The Rust expression of a derivation tag over the `x_` scalars (0 when
/// the parameter declares none).
fn tag_expr(p: &Param) -> String {
    p.tag
        .as_deref()
        .and_then(|text| Expr::parse(text).ok())
        .map_or("0usize".to_string(), |e| format!("({})", e.rust(&p.name)))
}

fn rust_wrapper(l: &Launcher, prefix: &str) -> String {
    // Buffers another parameter aliases: their pointer is bound once and
    // passed for both.
    let aliased: BTreeSet<&str> = l
        .params
        .iter()
        .filter(|p| p.kind == Kind::Alias)
        .filter_map(|p| p.of.as_deref())
        .collect();
    let mut bindings = String::new();
    let mut signature = vec!["stream: &::gufo_hip::Stream".to_string()];
    let conversions = extent_conversions(l, "    ");
    let mut checks = String::new();
    let mut args = Vec::new();
    let mut recorded = Vec::new();
    // Kernel-written indices: marked rewritten once every check passed.
    let mut commits = String::new();
    // Lists: length checks, per-element checks and recorded arguments.
    let count = l.list_count().unwrap_or_default();
    let mut lists = String::new();
    let mut elements = String::new();
    let mut listed = String::new();
    for p in &l.params {
        let n = &p.name;
        match (p.kind, p.elem, p.scalar) {
            (Kind::Scalar, _, Some(sc)) if p.list.is_some() => {
                signature.push(format!("{n}: &[{}]", sc.rust()));
                args.push(format!("{n}.as_ptr()"));
                let _ = writeln!(
                    lists,
                    "    if {n}.len() != x_{count} {{\n        return Err(::gufo_hip::LaunchError::InvalidArgument {{ param: \"{n}\", reason: \"list length differs from `{count}`\" }});\n    }}"
                );
                let bits = if sc == Scalar::Usize {
                    "v as u64"
                } else {
                    "u64::from(v)"
                };
                let _ = writeln!(
                    listed,
                    "        args.extend({n}.iter().map(|&v| l::Arg::scalar(\"{n}\", {bits})));"
                );
            }
            (Kind::Scalar, _, Some(sc)) => {
                signature.push(format!("{n}: {}", sc.rust()));
                if !p.contract_only {
                    args.push(n.clone());
                }
                let bits = match sc {
                    Scalar::Usize => format!("{n} as u64"),
                    Scalar::U32 | Scalar::Bool => format!("u64::from({n})"),
                    Scalar::I32 => format!("{n} as i64 as u64"),
                    Scalar::F32 => format!("u64::from({n}.to_bits())"),
                    Scalar::F64 => format!("{n}.to_bits()"),
                };
                recorded.push(format!("l::Arg::scalar(\"{n}\", {bits})"));
            }
            (Kind::Quant, _, _) => {
                let expr = |text: &Option<String>| {
                    Expr::parse(text.as_deref().unwrap_or_default())
                        .map(|e| e.rust(n))
                        .unwrap_or_default()
                };
                signature.push(format!("{n}: ::gufo_hip::QuantSlice<'_>"));
                let formats: Vec<String> = p
                    .formats
                    .iter()
                    .filter_map(|f| gufo_formats::GgmlType::from_name(f))
                    .map(|f| format!("::gufo_hip::GgmlType::{f:?}"))
                    .collect();
                let tail = if p.tail.is_some() {
                    expr(&p.tail)
                } else {
                    "0usize".into()
                };
                let _ = writeln!(
                    checks,
                    "    l::require_format(\"{n}\", &{n}, &[{}])?;\n    \
                     l::require_quant(stream, \"{n}\", &{n}, {}, {}, {tail})?;",
                    formats.join(", "),
                    expr(&p.rows),
                    expr(&p.cols)
                );
                if let Some(other) = &p.same_format {
                    let _ = writeln!(
                        checks,
                        "    l::require_same_format(\"{n}\", &{n}, \"{other}\", &{other})?;"
                    );
                }
                args.push(format!("{n}.bytes().as_ptr()"));
                recorded.push(format!(
                    "l::Arg::buffer(\"{n}\", Some({n}.bytes().allocation()), {n}.bytes().address(), {n}.len())"
                ));
                recorded.push(format!(
                    "l::Arg::scalar(\"{n}\", u64::from({n}.format().id()))"
                ));
            }
            (Kind::Format, _, _) => {
                let of = p.of.as_deref().unwrap_or_default();
                args.push(format!("{of}.format().id() as u16"));
            }
            (Kind::Const | Kind::Stream, _, _) => {}
            (Kind::Table, Some(e), _) => {
                let width = p.width.unwrap_or(1);
                signature.push(format!(
                    "{n}: Option<&::gufo_hip::RowTable<{}, {width}>>",
                    e.rust()
                ));
                let _ = writeln!(
                    checks,
                    "    if let Some(table) = {n} {{\n        l::require_in(stream, \"{n}\", &table.header(), 2)?;\n        if let Some(rows) = table.rows() {{\n            l::require_in(stream, \"{n}\", &rows, 0)?;\n        }}\n    }}"
                );
                args.push(format!(
                    "{n}.map_or(::std::ptr::null(), |t| t.header().as_ptr().cast())"
                ));
                recorded.push(format!(
                    "l::Arg::buffer(\"{n}\", {n}.map(|t| t.header().allocation()), \
                     {n}.map_or(0, |t| t.header().address()), {n}.map_or(0, |t| t.header().len()))"
                ));
                recorded.push(format!(
                    "l::Arg::buffer(\"{n}\", {n}.and_then(|t| t.rows()).map(|r| r.allocation()), \
                     {n}.and_then(|t| t.rows()).map_or(0, |r| r.address()), \
                     {n}.and_then(|t| t.rows()).map_or(0, |r| r.len()))"
                ));
            }
            (Kind::Alias, _, _) => {
                let of = p.of.as_deref().unwrap_or_default();
                let cast = if p.read_only {
                    "cast_const()"
                } else {
                    "cast()"
                };
                args.push(format!("{of}_ptr.{cast}"));
            }
            (Kind::Indices, _, _) => {
                let len = Expr::parse(p.len.as_deref().unwrap_or_default())
                    .map(|e| e.rust(n))
                    .unwrap_or_default();
                let below = Expr::parse(p.below.as_deref().unwrap_or_default())
                    .map(|e| e.rust(n))
                    .unwrap_or_default();
                signature.push(format!("{n}: ::gufo_hip::IndexSlice<'_>"));
                if p.mask.is_some() || p.padded || p.signed {
                    let _ = writeln!(
                        checks,
                        "    l::require_index_spec(stream, \"{n}\", &{n}, {len}, {below}, {}, {}, {})?;",
                        mask_literal(p),
                        p.padded,
                        p.signed
                    );
                } else {
                    let _ = writeln!(
                        checks,
                        "    l::require_indices(stream, \"{n}\", &{n}, {len}, {below})?;"
                    );
                }
                if let Some(source) = &p.derived_from {
                    let _ = writeln!(
                        checks,
                        "    l::require_derived(\"{n}\", &{n}, \"{source}\", &{source}, {} as u64)?;",
                        tag_expr(p)
                    );
                }
                let cast = if p.signed { ".cast::<i32>()" } else { "" };
                args.push(format!("{n}.values().as_ptr(){cast}"));
                recorded.push(format!(
                    "l::Arg::buffer(\"{n}\", Some({n}.values().allocation()), {n}.values().address(), {n}.len())"
                ));
            }
            (Kind::IndicesOut, _, _) => {
                let len = Expr::parse(p.len.as_deref().unwrap_or_default())
                    .map(|e| e.rust(n))
                    .unwrap_or_default();
                let below = Expr::parse(p.below.as_deref().unwrap_or_default())
                    .map(|e| e.rust(n))
                    .unwrap_or_default();
                signature.push(format!("mut {n}: ::gufo_hip::IndexSliceMut<'_>"));
                let _ = writeln!(
                    checks,
                    "    l::require_indices_out(stream, \"{n}\", &{n}, {len}, {below}, {}, {}, {})?;",
                    mask_literal(p),
                    p.padded,
                    p.signed
                );
                let derived = p
                    .derived_from
                    .as_ref()
                    .map_or("None".to_string(), |source| {
                        format!("Some({source}.derivation({} as u64))", tag_expr(p))
                    });
                let _ = writeln!(
                    commits,
                    "    // SAFETY: the kernel writes `{n}` in this launch, from the\n    \
                     // source launch.toml names (`derived_from`).\n    \
                     unsafe {{ l::commit(&mut {n}, {derived}) }};"
                );
                let cast = if p.signed { ".cast::<i32>()" } else { "" };
                args.push(format!("{n}.as_mut_ptr(){cast}"));
                recorded.push(format!(
                    "l::Arg::buffer(\"{n}\", Some({n}.allocation()), {n}.address(), {n}.len())"
                ));
            }
            (kind, Some(e), _) if p.list.is_some() => {
                let input = kind == Kind::In;
                let (view, require, ptr, null, iter, access) = if input {
                    (
                        "DeviceSlice",
                        "require_in",
                        "as_ptr()",
                        "::std::ptr::null()",
                        "iter",
                        "as_ref",
                    )
                } else {
                    (
                        "DeviceSliceMut",
                        "require_out",
                        "as_mut_ptr()",
                        "::std::ptr::null_mut()",
                        "iter_mut",
                        "as_mut",
                    )
                };
                let pointer = if input { "*const" } else { "*mut" };
                let element = format!("::gufo_hip::{view}<'_, {}>", e.rust());
                let element = if p.optional {
                    format!("Option<{element}>")
                } else {
                    element
                };
                let slice = if input { "&" } else { "&mut " };
                signature.push(format!("{n}: {slice}[{element}]"));
                let expr = Expr::parse(p.len.as_deref().unwrap_or_default())
                    .map(|e| e.rust(n))
                    .unwrap_or_default();
                let _ = writeln!(
                    lists,
                    "    if {n}.len() != x_{count} {{\n        return Err(::gufo_hip::LaunchError::InvalidArgument {{ param: \"{n}\", reason: \"list length differs from `{count}`\" }});\n    }}"
                );
                if p.optional {
                    let _ = writeln!(
                        elements,
                        "        if let Some(view) = &{n}[i] {{\n            l::{require}(stream, \"{n}\", view, {expr})?;\n        }}"
                    );
                    let _ = writeln!(
                        bindings,
                        "    let {n}_ptrs: Vec<{pointer} {}> = {n}.{iter}().map(|v| v.{access}().map_or({null}, |v| v.{ptr})).collect();",
                        e.rust()
                    );
                    let _ = writeln!(
                        listed,
                        "        args.extend({n}.iter().map(|v| l::Arg::buffer(\"{n}\", v.as_ref().map(|v| v.allocation()), v.as_ref().map_or(0, |v| v.address()), v.as_ref().map_or(0, |v| v.len()))));"
                    );
                } else {
                    let _ = writeln!(
                        elements,
                        "        l::{require}(stream, \"{n}\", &{n}[i], {expr})?;"
                    );
                    let _ = writeln!(
                        bindings,
                        "    let {n}_ptrs: Vec<{pointer} {}> = {n}.{iter}().map(|v| v.{ptr}).collect();",
                        e.rust()
                    );
                    let _ = writeln!(
                        listed,
                        "        args.extend({n}.iter().map(|v| l::Arg::buffer(\"{n}\", Some(v.allocation()), v.address(), v.len())));"
                    );
                }
                args.push(format!("{n}_ptrs.as_ptr()"));
            }
            (kind, Some(e), _) => {
                let (view, require, ptr, null, access) = if kind == Kind::In {
                    (
                        "DeviceSlice",
                        "require_in",
                        "as_ptr()",
                        "::std::ptr::null()",
                        "as_ref",
                    )
                } else {
                    (
                        "DeviceSliceMut",
                        "require_out",
                        "as_mut_ptr()",
                        "::std::ptr::null_mut()",
                        "as_mut",
                    )
                };
                let ty = format!("::gufo_hip::{view}<'_, {}>", e.rust());
                let binding = if kind == Kind::In { "" } else { "mut " };
                let expr = Expr::parse(p.len.as_deref().unwrap_or_default())
                    .map(|e| e.rust(n))
                    .unwrap_or_default();
                if p.optional {
                    signature.push(format!("{binding}{n}: Option<{ty}>"));
                    let _ = writeln!(
                        checks,
                        "    if let Some(view) = &{n} {{\n        l::{require}(stream, \"{n}\", view, {expr})?;\n    }}"
                    );
                    args.push(format!("{n}.{access}().map_or({null}, |v| v.{ptr})"));
                    recorded.push(format!(
                        "l::Arg::buffer(\"{n}\", {n}.as_ref().map(|v| v.allocation()), \
                         {n}.as_ref().map_or(0, |v| v.address()), {n}.as_ref().map_or(0, |v| v.len()))"
                    ));
                } else {
                    signature.push(format!("{binding}{n}: {ty}"));
                    let _ = writeln!(checks, "    l::{require}(stream, \"{n}\", &{n}, {expr})?;");
                    if p.host_visible {
                        let _ = writeln!(
                            checks,
                            "    if !{n}.allocation().is_host_aliased() {{\n        return Err(::gufo_hip::LaunchError::InvalidArgument {{ param: \"{n}\", reason: \"the launcher writes it from the host: memory the host addresses at its device address only\" }});\n    }}"
                        );
                    }
                    if aliased.contains(n.as_str()) {
                        let _ = writeln!(bindings, "    let {n}_ptr = {n}.{ptr};");
                        args.push(format!("{n}_ptr"));
                    } else {
                        args.push(format!("{n}.{ptr}"));
                    }
                    recorded.push(format!(
                        "l::Arg::buffer(\"{n}\", Some({n}.allocation()), {n}.address(), {n}.len())"
                    ));
                }
            }
            _ => unreachable!("validated manifest"),
        }
    }
    let (ret, finish) = match l.returns {
        Returns::Void => ("()", "finish_void"),
        Returns::Supported => ("::gufo_hip::Launch", "finish"),
    };
    let mut s = String::new();
    let _ = writeln!(s, "\n/// {}\n///\n/// C++ launcher: `{}`.", l.doc, l.cpp);
    let _ = writeln!(s, "#[allow(clippy::too_many_arguments)]");
    let _ = writeln!(
        s,
        "pub fn {}(\n    {},\n) -> Result<{ret}, ::gufo_hip::LaunchError> {{",
        l.name,
        signature.join(",\n    ")
    );
    let _ = writeln!(
        s,
        "    use ::gufo_hip::launch as l;\n    l::begin(stream)?;"
    );
    s.push_str(&conversions);
    let mut element_requirements = String::new();
    for requirement in &l.requires {
        if let Ok(relation) = Relation::parse(requirement) {
            let (target, indent) = if per_element(l, &relation) {
                (&mut element_requirements, "        ")
            } else {
                (&mut s, "    ")
            };
            let _ = writeln!(
                target,
                "{indent}l::precondition({}, \"{}\", \"{requirement}\")?;",
                relation.rust(&l.name),
                l.cpp
            );
        }
    }
    if !count.is_empty() {
        s.push_str(&lists);
        let _ = write!(
            s,
            "    #[allow(clippy::needless_range_loop)] // lists and list scalars share `i`\n    \
             for i in 0..x_{count} {{\n{}{element_requirements}{elements}    }}\n",
            element_conversions(l, "        ")
        );
    }
    s.push_str(&checks);
    s.push_str(&commits);
    // Graph capture retains the arguments' allocations; graph validation
    // compares them with the capture and returns without launching.
    let replay = match l.returns {
        Returns::Void => "Some(_)",
        Returns::Supported => "Some(result)",
    };
    let early = match l.returns {
        Returns::Void => "Ok(())",
        Returns::Supported => "Ok(result)",
    };
    if count.is_empty() {
        let _ = writeln!(
            s,
            "    if stream.is_recording()\n        && let {replay} = l::record(\n            stream,\n            \"{}\",\n            &[{}],\n        )?\n    {{\n        return {early};\n    }}",
            l.cpp,
            if recorded.is_empty() {
                String::new()
            } else {
                format!(
                    "\n                {},\n            ",
                    recorded.join(",\n                ")
                )
            }
        );
    } else {
        let items: String = recorded
            .iter()
            .map(|r| format!("            {r},\n"))
            .collect();
        let replayed = match l.returns {
            Returns::Void => format!("l::record(stream, \"{}\", &args)?.is_some()", l.cpp),
            Returns::Supported => {
                format!("let {replay} = l::record(stream, \"{}\", &args)?", l.cpp)
            }
        };
        let _ = writeln!(
            s,
            "    if stream.is_recording() {{\n        let mut args: Vec<l::Arg<'_>> = vec![\n{items}        ];\n{listed}        if {replayed} {{\n            return {early};\n        }}\n    }}",
        );
    }
    s.push_str(&bindings);
    let _ = writeln!(
        s,
        "    // SAFETY: every buffer was checked above to belong to `stream` and to\n    \
         // cover the extent launch.toml declares; the shim cannot unwind.\n    \
         let raw = unsafe {{ ffi::{prefix}{}({}) }};\n    l::{finish}(stream, raw, \"{}\")\n}}",
        l.name,
        with_last(&args, "stream.as_raw()"),
        l.cpp
    );
    s
}

