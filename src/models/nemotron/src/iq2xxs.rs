/// Words of the IQ2_XXS grid as BF16 (`kIq2xxsGridWords`): 256 entries of
/// four words, each word two consecutive magnitudes (the lower one in the
/// low half).
pub const IQ2XXS_GRID_WORDS: usize = 256 * 4;

/// Expands [`IQ2XXS_GRID`] (eight u8 magnitudes per entry) into BF16 pairs
/// (`Iq2xxsGridBf16`); every magnitude is exact in BF16, so its encoding is
/// the upper half of the F32 one.
pub fn iq2xxs_grid_bf16() -> [u32; IQ2XXS_GRID_WORDS] {
    let mut words = [0u32; IQ2XXS_GRID_WORDS];
    for (e, entry) in IQ2XXS_GRID.iter().enumerate() {
        for p in 0..4 {
            let mut pair = 0u32;
            for h in 0..2 {
                let magnitude = ((entry >> (8 * (2 * p + h))) & 0xFF) as f32;
                pair |= (magnitude.to_bits() >> 16) << (16 * h);
            }
            words[e * 4 + p] = pair;
        }
    }
    words
}

/// Bytes of one IQ2_XXS super-block of 256 values (`kIq2xxsBlockBytes`).
pub const IQ2XXS_BLOCK_BYTES: usize = 66;

/// Dequantizes `dst.len()` values (a multiple of 256) as ggml's
/// `dequantize_row_iq2_xxs`: per super-block an F16 scale, then per 32
/// values four grid indices and a word of seven-bit sign groups (their
/// parity gives the eighth sign) and a four-bit group scale.
///
/// # Panics
/// When `src` holds fewer blocks than `dst` needs.
pub fn dequantize_iq2xxs(src: &[u8], dst: &mut [f32]) {
    let blocks = src.as_chunks::<IQ2XXS_BLOCK_BYTES>().0;
    for (block, values) in blocks.iter().zip(dst.as_chunks_mut::<256>().0) {
        let d = gufo_formats::dequant::f16_to_f32(u16::from_le_bytes([block[0], block[1]]));
        for (group, out) in values.as_chunks_mut::<32>().0.iter_mut().enumerate() {
            let q = &block[2 + 8 * group..2 + 8 * group + 8];
            let aux = u32::from_le_bytes([q[4], q[5], q[6], q[7]]);
            let db = d * (0.5 + (aux >> 28) as f32) * 0.25;
            for (l, eight) in out.as_chunks_mut::<8>().0.iter_mut().enumerate() {
                let grid = IQ2XXS_GRID[usize::from(q[l])].to_le_bytes();
                let bits = (aux >> (7 * l)) & 127;
                // ksigns_iq2xs: the seven bits and their parity.
                let signs = bits | ((bits.count_ones() & 1) << 7);
                for (j, value) in eight.iter_mut().enumerate() {
                    let sign = if signs & (1 << j) != 0 { -1.0 } else { 1.0 };
                    *value = db * f32::from(grid[j]) * sign;
                }
            }
        }
    }
}
