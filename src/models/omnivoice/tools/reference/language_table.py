#!/usr/bin/env python3
"""Generates language_table.inc from OmniVoice's language map.

Usage: language_table.py OUTPUT_INC

Needs the omnivoice package (Apache-2.0). Writes {name, id} pairs sorted by
the lowercase name, as omnivoice.utils.lang_map.LANG_NAME_TO_ID holds them.
"""
import subprocess
import sys

from omnivoice.utils.lang_map import LANG_NAME_TO_ID


def escape(text):
    return text.replace("\\", "\\\\").replace('"', '\\"')


def main():
    output = sys.argv[1]
    names = sorted(LANG_NAME_TO_ID, key=lambda name: name.encode("utf-8"))
    revision = subprocess.run(
        ["git", "-C", __import__("omnivoice").__path__[0], "rev-parse", "--short", "HEAD"],
        capture_output=True, text=True).stdout.strip() or "unknown"
    with open(output, "w", encoding="utf-8") as stream:
        stream.write("// Generated by tools/reference/language_table.py from\n"
                     "// omnivoice/utils/lang_map.py of k2-fsa/OmniVoice "
                     f"{revision} (Apache-2.0).\n// Do not edit.\n")
        for name in names:
            stream.write(f'{{"{escape(name)}", "{LANG_NAME_TO_ID[name]}"}},\n')
    print(f"{len(names)} languages, {len(set(LANG_NAME_TO_ID.values()))} IDs -> {output}")


if __name__ == "__main__":
    main()
