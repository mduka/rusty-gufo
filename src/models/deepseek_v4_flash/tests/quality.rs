fn load(dspark: bool) -> Engine {
    let support = common::dspark_path();
    Engine::open(&common::model_path(), dspark.then_some(support.as_path())).unwrap()
}

/// A session in the engine's mode: speculative with a support model.
fn session(engine: &mut Engine, context: u32) -> Session {
    let speculative = engine.dspark.is_some();
    engine.create_session(context, speculative).unwrap()
}

fn tokenize(engine: &Engine, text: &str) -> Vec<i32> {
    let mut tokens = Vec::new();
    engine.vocab.tokenize(text.as_bytes(), &mut tokens);
    tokens
}

/// `Model::EncodeChat(system, prompt)`.
fn chat(engine: &Engine, system: &str, prompt: &str) -> Vec<i32> {
    let mut tokens = Vec::new();
    engine
        .vocab
        .encode_chat(system.as_bytes(), prompt.as_bytes(), &mut tokens);
    tokens
}

fn logits(session: &Session) -> Vec<f32> {
    session.logits().unwrap().to_vec()
}

fn repeat(pattern: &[i32], count: usize) -> Vec<i32> {
    (0..count).map(|i| pattern[i % pattern.len()]).collect()
}

fn sha256(bytes: &[u8]) -> String {
    Sha256::digest(bytes)
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect()
}

fn float_bytes(values: &[f32]) -> Vec<u8> {
    values.iter().flat_map(|v| v.to_le_bytes()).collect()
}

/// 1 plus the number of logits above `token`'s.
fn rank(logits: &[f32], token: i32) -> usize {
    let value = logits[token as usize];
    1 + logits.iter().filter(|&&v| v > value).count()
}

/// The first maximum (`std::max_element`).
fn top(logits: &[f32]) -> usize {
    let mut best = 0;
    for (i, &v) in logits.iter().enumerate() {
        if v > logits[best] {
            best = i;
        }
    }
    best
}

struct Comparison {
    finite: bool,
    rmse: f64,
    cosine: f64,
    max_error: f32,
}

fn compare(candidate: &[f32], reference: &[f32]) -> Comparison {
    assert_eq!(candidate.len(), reference.len(), "logit shape");
    let (mut squared, mut dot, mut candidate_norm, mut reference_norm) = (0.0, 0.0, 0.0, 0.0);
    let mut max_error = 0.0f32;
    let mut finite = true;
    for (&c, &r) in candidate.iter().zip(reference) {
        finite &= c.is_finite() && r.is_finite();
        let delta = f64::from(c) - f64::from(r);
        squared += delta * delta;
        dot += f64::from(c) * f64::from(r);
        candidate_norm += f64::from(c) * f64::from(c);
        reference_norm += f64::from(r) * f64::from(r);
        max_error = max_error.max((c - r).abs());
    }
    let denominator = (candidate_norm * reference_norm).sqrt();
    Comparison {
        finite,
        rmse: (squared / candidate.len() as f64).sqrt(),
        cosine: if denominator > f64::MIN_POSITIVE {
            dot / denominator
        } else {
            0.0
        },
        max_error,
    }
}

/// Disjoint mutable borrows of `sessions` in the order of `indices`.
fn pick<'a>(sessions: &'a mut [Session], indices: &[usize]) -> Vec<&'a mut Session> {
    let mut slots: Vec<Option<&mut Session>> = sessions.iter_mut().map(Some).collect();
    indices
        .iter()
        .map(|&i| slots[i].take().expect("distinct sessions"))
        .collect()
}

/// One `DsparkStepBatch` over `(session, max_tokens)`, draft limit 7; the
/// emitted tokens in item order.
fn dspark_batch(engine: &mut Engine, members: Vec<(&mut Session, usize)>) -> Vec<Vec<i32>> {
    let mut items: Vec<DsparkItem<'_>> = members
        .into_iter()
        .map(|(session, max_tokens)| DsparkItem {
            session,
            max_tokens,
            max_draft_tokens: 7,
            sampler: None,
            stop_at_eos: false,
            emitted: Vec::new(),
        })
        .collect();
    Session::dspark_step_batch(engine, &mut items).unwrap();
    items.into_iter().map(|item| item.emitted).collect()
}

/// `Session::DsparkStep(max_tokens, max_draft_tokens)`.
fn dspark_step(
    engine: &mut Engine,
    session: &mut Session,
    max_tokens: usize,
    draft: u32,
) -> Vec<i32> {
    session
        .dspark_step(engine, max_tokens, draft, None, false)
        .unwrap()
}

/// The session test of the C++ `main`: prefill, two greedy steps and a
/// snapshot restored at the prompt frontier.
fn session_round_trip(engine: &mut Engine) {
    let prompt = chat(
        engine,
        "You are a concise assistant.",
        "Reply with one word.",
    );
    assert!(!prompt.is_empty(), "chat prompt tokenization");
    let mut s = session(engine, 4096);
    s.sync(engine, &prompt).unwrap();
    assert_eq!(s.position(), prompt.len(), "prefill position");
    let frontier = logits(&s);
    assert!(frontier.iter().all(|v| v.is_finite()), "finite logits");
    let checkpoint = s.position();
    let first = s.argmax();
    assert!(first >= 0, "first greedy token");
    assert!(
        !engine.vocab.token_text(first).is_empty(),
        "first token text"
    );
    let snapshot = s.save_snapshot(engine).unwrap();
    assert!(!snapshot.is_empty(), "snapshot payload");
    s.eval(engine, first).unwrap();
    let second = s.argmax();
    assert!(second >= 0, "second greedy token");
    s.eval(engine, second).unwrap();
    assert_eq!(s.position(), prompt.len() + 2, "decode position");
    s.restore_snapshot(engine, &snapshot).unwrap();
    assert_eq!(s.position(), checkpoint, "restored position");
    assert_eq!(s.argmax(), first, "restored greedy token");
    assert!(logits(&s) == frontier, "restored logits");
    println!("DeepSeek V4 Flash model/session test passed");
}

fn pinned_trajectory(engine: &mut Engine) {
    let prompt = tokenize(engine, TRAJECTORY_PROMPT);
    let mut s = session(engine, 512);
    s.sync(engine, &prompt).unwrap();
    let (mut top1, mut rank_sum, mut worst) = (0, 0, 0);
    let mut fingerprint = Sha256::new();
    for &expected in &PINNED_TRAJECTORY {
        let row = logits(&s);
        fingerprint.update(float_bytes(&row));
        assert!((expected as usize) < row.len(), "trajectory token range");
        let r = rank(&row, expected);
        top1 += usize::from(s.argmax() == expected);
        rank_sum += r;
        worst = worst.max(r);
        s.eval(engine, expected).unwrap();
    }
    let digest: String = fingerprint
        .finalize()
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect();
    println!(
        "Pinned DS4 trajectory: top1={top1}/128 rank_sum={rank_sum} worst_rank={worst} logits_sha256={digest}"
    );
    assert!(top1 >= 116, "128-token top-1 agreement");
    assert!(rank_sum <= 142, "128-token aggregate rank");
    assert!(worst <= 3, "128-token worst rank");
}

fn session_bounds(engine: &mut Engine) {
    let dspark = engine.dspark.is_some();
    let mut s = session(engine, 32);
    assert!(
        s.prefill_capacity() > 0 && s.prefill_capacity() <= 32,
        "prefill allocation fits the session context"
    );
    assert!(
        s.argmax() == -1 && s.logits().is_none(),
        "uninitialized checkpoint cannot expose logits"
    );
    assert!(
        s.eval(engine, 1).is_err(),
        "decode requires initialized target state"
    );
    if dspark {
        assert!(
            s.dspark_step(engine, 32, 5, None, false).is_err(),
            "DSpark requires initialized target state"
        );
    }
    let mut prompt = tokenize(engine, TRAJECTORY_PROMPT);
    prompt.resize(30, 0);
    s.sync(engine, &prompt).unwrap();
    let frontier = logits(&s);
    let mut invalid = prompt.clone();
    invalid[0] = -1;
    assert!(
        s.sync(engine, &invalid).is_err() && s.eval(engine, engine.vocab.len() as i32).is_err(),
        "invalid token IDs are rejected before GPU execution"
    );
    assert!(
        logits(&s) == frontier,
        "argument rejection preserves the valid checkpoint"
    );
    while s.position() < s.context_size() as usize {
        let token = s.argmax();
        s.eval(engine, token).unwrap();
    }
    assert!(
        s.eval(engine, 1).is_err() && s.position() == 32,
        "decode cannot advance past the allocated context"
    );
    if dspark {
        assert!(
            s.dspark_step(engine, 32, 5, None, false).is_err() && s.position() == 32,
            "DSpark fallback cannot overrun a full context"
        );
    }
}

fn wide_prefill(engine: &mut Engine) {
    let tokens = repeat(&tokenize(engine, TRAJECTORY_PROMPT), 2048);
    let mut run = |context: u32| {
        let mut s = session(engine, context);
        s.sync(engine, &tokens).unwrap();
        let mut trajectory = Vec::new();
        for step in 0..4 {
            assert_eq!(s.position(), 2048 + step, "wide prefill frontier");
            let row = logits(&s);
            assert!(
                row.iter().all(|v| v.is_finite()),
                "wide prefill finite logits"
            );
            trajectory.extend_from_slice(&row);
            if step < 3 {
                let token = s.argmax();
                s.eval(engine, token).unwrap();
            }
        }
        trajectory
    };
    let reference = run(4096);
    let wide = run(262_144);
    assert!(
        reference == wide,
        "2K prefill and continuation retain exact logits with a 262K capacity"
    );
    println!(
        "Wide prefill fingerprint {}",
        sha256(&float_bytes(&reference))
    );
}

/// Batched prefill of `tokens` against a sequential one from `start`
/// tokens, within the C++ envelopes.
fn prefill_against_sequential(
    engine: &mut Engine,
    tokens: &[i32],
    start: usize,
    context: u32,
) -> String {
    let mut batched = session(engine, context);
    batched.sync(engine, tokens).unwrap();
    let batched_logits = logits(&batched);
    drop(batched);
    let mut sequential = session(engine, context);
    sequential.sync(engine, &tokens[..start]).unwrap();
    for &token in &tokens[start..] {
        sequential.eval(engine, token).unwrap();
    }
    let sequential_logits = logits(&sequential);
    let c = compare(&batched_logits, &sequential_logits);
    let sequential_top = top(&sequential_logits);
    let choice_rank = rank(&batched_logits, sequential_top as i32);
    let report = format!(
        "rmse={} cosine={} max_error={} top1_match={} sequential_choice_rank={choice_rank}",
        c.rmse,
        c.cosine,
        c.max_error,
        u8::from(top(&batched_logits) == sequential_top)
    );
    assert!(c.finite, "prefill finite logits");
    assert!(c.rmse <= 1.12, "prefill RMSE envelope: {report}");
    assert!(c.cosine >= 0.979, "prefill cosine envelope: {report}");
    assert!(
        c.max_error <= 5.0,
        "prefill maximum error envelope: {report}"
    );
    assert!(choice_rank <= 3, "prefill sequential choice rank: {report}");
    report
}

fn batched_prefill(engine: &mut Engine) {
    let prompt = tokenize(engine, TRAJECTORY_PROMPT);
    let mut tokens = prompt.clone();
    for _ in 0..2 {
        tokens.extend_from_slice(&PINNED_TRAJECTORY);
    }
    let report = prefill_against_sequential(engine, &tokens, prompt.len(), 4096);
    println!(
        "Batched prefill ({} tokens) vs sequential: {report}",
        tokens.len()
    );
}

fn conversational_prefill(engine: &mut Engine) {
    let prompt = tokenize(engine, TRAJECTORY_PROMPT);
    for width in [32, 64, 96] {
        let mut tokens = prompt.clone();
        let mut index = 0;
        while tokens.len() < width {
            tokens.push(PINNED_TRAJECTORY[index % PINNED_TRAJECTORY.len()]);
            index += 1;
        }
        let report = prefill_against_sequential(engine, &tokens, 1, 512);
        println!("Conversational prefill ({width} tokens) vs sequential: {report}");
    }
}

#[derive(Default)]
struct BatchQuality {
    comparisons: usize,
    top1: usize,
    worst_rmse: f64,
    worst_cosine: f64,
    worst_max_error: f32,
    worst_rank: usize,
}

impl BatchQuality {
    fn compare(&mut self, index: usize, batched: &Session, sequential: &Session) {
        let batched_token = batched.argmax();
        let sequential_token = sequential.argmax();
        let batched_logits = logits(batched);
        let c = compare(&batched_logits, &logits(sequential));
        let choice_rank = rank(&batched_logits, sequential_token);
        self.comparisons += 1;
        self.top1 += usize::from(batched_token == sequential_token);
        self.worst_rmse = self.worst_rmse.max(c.rmse);
        self.worst_cosine = self.worst_cosine.min(c.cosine);
        self.worst_max_error = self.worst_max_error.max(c.max_error);
        self.worst_rank = self.worst_rank.max(choice_rank);
        if batched_token != sequential_token
            || c.rmse > 0.85
            || c.cosine < 0.99
            || c.max_error > 4.5
            || choice_rank > 3
        {
            println!(
                "Session batch quality detail: member={index} position={} batched={batched_token} sequential={sequential_token} rmse={} cosine={} max_error={} sequential_choice_rank={choice_rank}",
                batched.position(),
                c.rmse,
                c.cosine,
                c.max_error
            );
        }
        assert!(c.finite, "session batch finite logits");
        assert!(c.rmse <= 0.85, "session batch RMSE envelope");
        assert!(c.cosine >= 0.99, "session batch cosine envelope");
        assert!(c.max_error <= 4.5, "session batch maximum error envelope");
        assert!(choice_rank <= 3, "session batch sequential choice rank");
    }
}

fn session_batch(engine: &mut Engine) {
    const PROMPTS: [&str; 8] = [
        "Explain virtual memory in one paragraph.",
        "Write a short C++ function that adds two integers.",
        "What causes ocean tides? Answer concisely.",
        "List three practical ways to reduce database query latency.",
        "Describe how a hash table handles collisions.",
        "Give one advantage of immutable data structures.",
        "Why do compilers inline small functions?",
        "Name two ways to reduce network request latency.",
    ];
    const PROMPT_TOKENS: [usize; 8] = [32, 48, 64, 96, 128, 160, 192, 256];
    let prompts: Vec<Vec<i32>> = PROMPTS
        .iter()
        .zip(PROMPT_TOKENS)
        .map(|(text, length)| {
            let mut prompt = chat(engine, "You are a concise assistant.", text);
            let mut token = 0;
            while prompt.len() < length {
                prompt.push(PINNED_TRAJECTORY[token % PINNED_TRAJECTORY.len()]);
                token += 1;
            }
            prompt
        })
        .collect();
    let reset = |engine: &mut Engine| {
        let mut batched = Vec::new();
        let mut sequential = Vec::new();
        for prompt in &prompts {
            let mut b = session(engine, 512);
            let mut s = session(engine, 512);
            b.sync(engine, prompt).unwrap();
            s.sync(engine, prompt).unwrap();
            assert_eq!(b.argmax(), s.argmax(), "session batch initial greedy token");
            batched.push(b);
            sequential.push(s);
        }
        (batched, sequential)
    };
    let (mut batched, mut sequential) = reset(engine);

    // Duplicate sessions cannot be expressed: `eval_batch` borrows each one
    // mutably.
    let positions = (batched[0].position(), batched[1].position());
    let (token0, token1) = (batched[0].argmax(), batched[1].argmax());
    let vocabulary = engine.vocab.len() as i32;
    {
        let [b0, b1] = pick(&mut batched, &[0, 1]).try_into().ok().unwrap();
        assert!(
            Session::eval_batch(engine, &mut [(b0, token0), (b1, vocabulary)]).is_err(),
            "session batch rejects invalid tokens"
        );
    }
    assert_eq!(
        (batched[0].position(), batched[1].position()),
        positions,
        "session batch preflight preserves positions"
    );
    batched[1].set_cancellation(Some(Box::new(|| true)));
    {
        let [b0, b1] = pick(&mut batched, &[0, 1]).try_into().ok().unwrap();
        assert!(
            Session::eval_batch(engine, &mut [(b0, token0), (b1, token1)]).is_err(),
            "session batch rejects cancelled sessions"
        );
    }
    batched[1].set_cancellation(None);
    assert_eq!(
        (batched[0].position(), batched[1].position()),
        positions,
        "session batch preflight preserves positions"
    );

    let mut quality = BatchQuality {
        worst_cosine: 1.0,
        ..BatchQuality::default()
    };
    let mut advance = |engine: &mut Engine,
                       batched: &mut [Session],
                       sequential: &mut [Session],
                       members: &[usize]| {
        let mut tokens = Vec::new();
        for &index in members {
            let token = sequential[index].argmax();
            sequential[index].eval(engine, token).unwrap();
            tokens.push(token);
        }
        let mut items: Vec<(&mut Session, i32)> =
            pick(batched, members).into_iter().zip(tokens).collect();
        Session::eval_batch(engine, &mut items).unwrap();
        drop(items);
        for &index in members {
            assert_eq!(
                batched[index].position(),
                sequential[index].position(),
                "session batch position"
            );
            quality.compare(index, &batched[index], &sequential[index]);
        }
    };
    advance(engine, &mut batched, &mut sequential, &[0, 1, 2, 3, 4, 5]);
    drop((batched, sequential));
    let (mut batched, mut sequential) = reset(engine);
    for _ in 0..3 {
        advance(engine, &mut batched, &mut sequential, &[0, 1, 2, 3]);
    }
    advance(engine, &mut batched, &mut sequential, &[0, 2]);
    advance(
        engine,
        &mut batched,
        &mut sequential,
        &[0, 1, 2, 3, 4, 5, 6, 7],
    );
    let token = sequential[0].argmax();
    sequential[0].eval(engine, token).unwrap();
    batched[0].eval(engine, token).unwrap();
    quality.compare(0, &batched[0], &sequential[0]);
    println!(
        "DeepSeek V4 session batch quality: top1={}/{} worst_rmse={} worst_cosine={} worst_max_error={} worst_sequential_choice_rank={}",
        quality.top1,
        quality.comparisons,
        quality.worst_rmse,
        quality.worst_cosine,
        quality.worst_max_error,
        quality.worst_rank
    );
}

/// DSpark C1 (or AR C2 when `batched`) against AR across ratio-4's
/// 512-entry sparse attention boundary: tokens and full logits exact.
fn indexer_boundary(engine: &mut Engine, batched: bool) {
    let prompt = chat(engine, "", BOUNDARY_PROMPT);
    assert_eq!(prompt.len(), 2035, "indexer boundary prompt token identity");
    let mut ar = engine.create_session(133_760, false).unwrap();
    let mut spec = engine.create_session(133_760, !batched).unwrap();
    let mut peer = batched.then(|| engine.create_session(133_760, false).unwrap());
    // HTTP's stable prompt checkpoint followed by its final three tokens.
    let prefix = &prompt[..prompt.len() - 3];
    for s in [Some(&mut ar), Some(&mut spec), peer.as_mut()]
        .into_iter()
        .flatten()
    {
        s.sync(engine, prefix).unwrap();
        s.sync(engine, &prompt).unwrap();
    }
    let mut worst = 0.0f32;
    let mut compare_rows =
        |generated: usize, ar: &Session, spec: &Session, peer: Option<&Session>| {
            let a = logits(ar);
            let b = logits(spec);
            if let Some(peer) = peer {
                assert!(logits(peer) == b, "independent AR batch rows agree");
            }
            let c = compare(&a, &b);
            assert!(c.finite, "finite replay logits");
            if c.max_error != 0.0 && worst == 0.0 {
                println!(
                    "Indexer boundary first logit difference at={generated} max_error={} rmse={}",
                    c.max_error, c.rmse
                );
            }
            worst = worst.max(c.max_error);
            c.max_error == 0.0
        };
    let mut exact = compare_rows(0, &ar, &spec, peer.as_ref());
    let (mut generated, mut mismatches) = (0, 0);
    while generated < 128 {
        let emitted = match peer.as_mut() {
            Some(peer) => {
                let token = spec.argmax();
                Session::eval_batch(engine, &mut [(&mut spec, token), (peer, token)]).unwrap();
                vec![token]
            }
            None => dspark_step(engine, &mut spec, 128 - generated, 7),
        };
        assert!(!emitted.is_empty(), "DSpark replay progress");
        for token in emitted {
            let expected = ar.argmax();
            if token != expected {
                mismatches += 1;
                println!(
                    "Prompt replay mismatch at={generated} candidate={token} expected={expected}"
                );
            }
            ar.eval(engine, token).unwrap();
            generated += 1;
        }
        exact = compare_rows(generated, &ar, &spec, peer.as_ref()) && exact;
    }
    println!(
        "Indexer boundary {}: mismatches={mismatches}/128 max_error={worst}",
        if batched { "AR C2" } else { "DSpark C1" }
    );
    assert!(
        exact && mismatches == 0,
        "indexer boundary matches scalar tokens/logits"
    );
}

fn dspark_prompt_seed(engine: &mut Engine) {
    let prompt = chat(
        engine,
        "You are a helpful assistant",
        "The quick brown fox jumps over the lazy dog. Explain why.",
    );
    let mut s = session(engine, 512);
    s.sync(engine, &prompt).unwrap();
    let seeded = s.dspark_stats().context_tokens as usize;
    assert!(
        seeded >= prompt.len(),
        "DSpark prefill seeds the complete prompt"
    );
    let emitted = dspark_step(engine, &mut s, 32, 5);
    assert!(!emitted.is_empty(), "DSpark first step emitted tokens");
    let stats = s.dspark_stats();
    assert!(
        stats.context_tokens as usize >= prompt.len(),
        "first DSpark cycle retains complete prompt coverage"
    );
    assert_eq!(
        stats.steps, 1,
        "DSpark drafts on the first generation cycle"
    );
    assert_eq!(stats.anchors, 1, "DSpark records one target-known anchor");
    assert_eq!(
        stats.support_drafted, 3,
        "DSpark begins with three support rows"
    );
    assert_eq!(
        stats.verifier_rows, 4,
        "DSpark verifies anchor plus support rows"
    );
    let mut short_extension = prompt.clone();
    short_extension.push(emitted[0]);
    short_extension.push(s.argmax());
    drop(s);

    let mut extended = session(engine, 512);
    extended.sync(engine, &prompt).unwrap();
    extended.sync(engine, &short_extension).unwrap();
    assert_eq!(
        extended.dspark_stats().context_tokens as usize,
        short_extension.len(),
        "short checkpoint extension seeds and extends DSpark context"
    );
    dspark_step(engine, &mut extended, 32, 5);
    assert!(
        extended.dspark_stats().context_tokens as usize >= short_extension.len(),
        "first draft after extension seeds the captured suffix"
    );
    drop(extended);

    // A short output budget still permits a shorter useful draft.
    for concurrency in [1, 2] {
        let mut sessions: Vec<Session> = (0..concurrency)
            .map(|_| {
                let mut member = session(engine, prompt.len() as u32 + 5);
                member.sync(engine, &prompt).unwrap();
                member
            })
            .collect();
        let output = dspark_batch(engine, sessions.iter_mut().map(|s| (s, 4)).collect());
        for (s, emitted) in sessions.iter().zip(&output) {
            assert_eq!(
                s.dspark_stats().steps,
                1,
                "short request/context budget still exercises drafting"
            );
            assert!(
                !emitted.is_empty() && emitted.len() <= 4,
                "short draft stays within output and context bounds"
            );
        }
    }
}

fn dspark_snapshots(engine: &mut Engine) {
    let pattern = tokenize(engine, TRAJECTORY_PROMPT);
    for depth in [53, 4608, 16384] {
        let prompt = repeat(&pattern, depth);
        let mut source = session(engine, 20480);
        let mut fork = session(engine, 20480);
        source.sync(engine, &prompt).unwrap();
        // A fresh prefix and a controller with acceptance history.
        if depth == 53 {
            for _ in 0..8 {
                dspark_step(engine, &mut source, 8, 7);
            }
        }
        let snapshot = source.save_snapshot(engine).unwrap();
        assert_eq!(
            snapshot.len() as u64,
            source.payload_bytes(),
            "complete snapshot size accounting"
        );
        let saved_stats = source.dspark_stats();
        let saved_logits = logits(&source);
        fork.restore_snapshot(engine, &snapshot).unwrap();
        assert!(
            fork.dspark_stats() == saved_stats && logits(&fork) == saved_logits,
            "snapshot restores exact support statistics and target frontier"
        );
        for cycle in 0..12 {
            let budget = if cycle % 3 == 0 { 2 } else { 8 };
            let expected = dspark_step(engine, &mut source, budget, 7);
            let actual = dspark_step(engine, &mut fork, budget, 7);
            assert!(
                actual == expected
                    && logits(&source) == logits(&fork)
                    && source.dspark_stats() == fork.dspark_stats(),
                "snapshot continuation repeats tokens, logits, and controller outcomes exactly"
            );
        }
        let source_logits = logits(&source);
        fork.restore_snapshot(engine, &snapshot).unwrap();
        fork.begin_request();
        let reused = fork.dspark_stats();
        assert!(
            reused.steps == 0
                && reused.support_drafted == 0
                && reused.context_tokens == saved_stats.context_tokens,
            "prefix reuse resets request statistics and retains support coverage"
        );
        dspark_step(engine, &mut fork, 4, 7);
        assert_eq!(
            fork.dspark_stats().steps,
            1,
            "restored prefix drafts immediately"
        );
        assert!(
            logits(&source) == source_logits,
            "snapshot forks own independent caches"
        );

        assert!(
            fork.restore_snapshot(engine, &snapshot[..snapshot.len() - 1])
                .is_err(),
            "truncated support state is rejected"
        );
        let mut corrupt = snapshot.clone();
        corrupt[4] = 0; // unsupported payload version
        assert!(
            fork.restore_snapshot(engine, &corrupt).is_err(),
            "old snapshot layout is rejected"
        );
        fork.restore_snapshot(engine, &snapshot).unwrap();
        assert!(
            fork.dspark_stats() == saved_stats && logits(&fork) == saved_logits,
            "valid restore recovers after a rejected snapshot"
        );
        println!("DSpark exact snapshot continuation at depth {depth}");
    }
}

/// Every DSpark frontier against a scalar replay of its tokens: tokens and
/// full logits exact, including the scalar sampler's tie-breaking.
fn dspark_scalar_quality(engine: &mut Engine) {
    const PROMPTS: [&str; 4] = [
        "Continue the pattern for twenty more terms and briefly state the rule: \
         red, blue, blue, red, blue, blue, red,",
        "Return only JSON for a three-day study plan. Each day must contain a \
         topic, minutes, and one measurable goal.",
        "Write the opening paragraph of a science-fiction story set in a silent \
         railway station orbiting Jupiter.",
        "请用简洁的中文解释什么是推测解码，以及为什么草稿模型的接受率会影响性能。",
    ];
    const SCENARIOS: [(usize, usize); 8] = [
        (1, 0),
        (1, 2048),
        (1, 4096),
        (2, 4096),
        (4, 4096),
        (6, 4096),
        (8, 16384),
        (2, 16384),
    ];
    let pattern = tokenize(engine, TRAJECTORY_PROMPT);
    let mut quality_ok = true;
    for (concurrency, depth) in SCENARIOS {
        let (mut top1, mut greedy_matches, mut compared, mut rank_sum, mut worst_rank) =
            (0, 0, 0, 0, 0);
        let (mut worst_rmse, mut worst_cosine, mut worst_error) = (0.0f64, 1.0f64, 0.0f32);
        let context = (depth + 512) as u32;
        let prefix = repeat(&pattern, depth);
        let snapshot = (depth != 0).then(|| {
            let mut base = session(engine, context);
            base.sync(engine, &prefix).unwrap();
            base.save_snapshot(engine).unwrap()
        });
        let groups = if concurrency == 1 { PROMPTS.len() } else { 1 };
        let budget = if concurrency == 1 { 32 } else { 16 };
        for group in 0..groups {
            let prompts: Vec<Vec<i32>> = (0..concurrency)
                .map(|i| {
                    let mut prompt = prefix.clone();
                    prompt.extend(chat(engine, "", PROMPTS[(group + i) % PROMPTS.len()]));
                    prompt
                })
                .collect();
            let make_session = |engine: &mut Engine, member: usize| {
                let mut s = session(engine, context);
                if let Some(snapshot) = &snapshot {
                    s.restore_snapshot(engine, snapshot).unwrap();
                }
                s.sync(engine, &prompts[member]).unwrap();
                s
            };
            let mut speculative: Vec<Session> =
                (0..concurrency).map(|i| make_session(engine, i)).collect();
            let mut generated = vec![0usize; concurrency];
            let mut frontiers: Vec<Vec<(Vec<i32>, Vec<f32>)>> = vec![Vec::new(); concurrency];
            loop {
                let active: Vec<usize> = (0..concurrency)
                    .filter(|&i| generated[i] < budget)
                    .collect();
                if active.is_empty() {
                    break;
                }
                let members = pick(&mut speculative, &active)
                    .into_iter()
                    .zip(&active)
                    .map(|(s, &i)| (s, budget - generated[i]))
                    .collect();
                let emitted = dspark_batch(engine, members);
                for (&member, emitted) in active.iter().zip(emitted) {
                    assert!(
                        !emitted.is_empty() && emitted.len() <= budget - generated[member],
                        "scalar replay makes bounded progress"
                    );
                    generated[member] += emitted.len();
                    frontiers[member].push((emitted, logits(&speculative[member])));
                }
            }
            assert!(
                speculative
                    .iter()
                    .any(|s| s.dspark_stats().support_drafted > 0),
                "scalar replay exercises support drafting"
            );
            // Every frontier is kept; the speculative KV goes before the
            // replay, so C sessions are resident at a time.
            drop(speculative);
            for (member, member_frontiers) in frontiers.iter().enumerate() {
                let mut sequential = make_session(engine, member);
                let mut replayed = 0;
                for (tokens, candidate) in member_frontiers {
                    for &token in tokens {
                        greedy_matches += usize::from(token == sequential.argmax());
                        let row = logits(&sequential);
                        assert!(
                            (token as usize) < row.len(),
                            "replayed token is in the reference vocabulary"
                        );
                        let r = rank(&row, token);
                        top1 += usize::from(r == 1);
                        compared += 1;
                        rank_sum += r;
                        worst_rank = worst_rank.max(r);
                        sequential.eval(engine, token).unwrap();
                        replayed += 1;
                    }
                    let reference = logits(&sequential);
                    let c = compare(candidate, &reference);
                    assert!(c.finite, "scalar replay finite frontier logits");
                    if c.max_error != 0.0 {
                        let worst_token = (0..candidate.len())
                            .max_by(|&a, &b| {
                                (candidate[a] - reference[a])
                                    .abs()
                                    .total_cmp(&(candidate[b] - reference[b]).abs())
                            })
                            .unwrap_or(0);
                        println!(
                            "Replay detail C={concurrency} depth={depth} member={member} generated={replayed} error_token={worst_token} candidate={} reference={} rmse={}",
                            candidate[worst_token], reference[worst_token], c.rmse
                        );
                    }
                    worst_error = worst_error.max(c.max_error);
                    worst_rmse = worst_rmse.max(c.rmse);
                    worst_cosine = worst_cosine.min(c.cosine);
                }
                assert_eq!(replayed, budget, "scalar replay checks the complete budget");
            }
        }
        println!(
            "DSpark scalar replay C{concurrency} depth={depth}: top1={top1}/{compared} rank_sum={rank_sum} worst_rank={worst_rank} rmse={worst_rmse} cosine={worst_cosine} max_error={worst_error}"
        );
        // Verification preserves scalar arithmetic, including the scalar
        // sampler's tie-breaking rule.
        let token_quality = greedy_matches == compared;
        let logit_quality = worst_error == 0.0;
        quality_ok &= token_quality && logit_quality;
        if !token_quality || !logit_quality {
            println!(
                "Replay gate C={concurrency} depth={depth} token_quality={} logit_quality={}",
                u8::from(token_quality),
                u8::from(logit_quality)
            );
        }
    }
    assert!(
        quality_ok,
        "every scalar replay scenario matches scalar tokens and logits"
    );
}

type Observation = (Vec<i32>, Vec<f32>, DsparkStats, usize);

fn concurrent_policy_snapshot(engine: &mut Engine) {
    for concurrency in [2, 8] {
        let prompt = tokenize(engine, TRAJECTORY_PROMPT);
        let mut sessions: Vec<Session> = (0..concurrency)
            .map(|_| {
                let mut s = session(engine, 512);
                s.sync(engine, &prompt).unwrap();
                s
            })
            .collect();
        // C2 snapshots a partial four-cycle window; C8 a cohort whose
        // short-context verification cost cannot be repaid even at full
        // acceptance.
        for _ in 0..(if concurrency == 2 { 6 } else { 3 }) {
            dspark_batch(engine, sessions.iter_mut().map(|s| (s, 8)).collect());
        }
        let snapshots: Vec<Vec<u8>> = sessions
            .iter()
            .map(|s| s.save_snapshot(engine).unwrap())
            .collect();
        let continue_requests = |engine: &mut Engine, sessions: &mut [Session]| {
            let mut observations: Vec<Observation> = Vec::new();
            for _ in 0..8 {
                let emitted = dspark_batch(engine, sessions.iter_mut().map(|s| (s, 8)).collect());
                for (s, emitted) in sessions.iter().zip(emitted) {
                    observations.push((emitted, logits(s), s.dspark_stats(), s.position()));
                }
            }
            observations
        };
        let expected = continue_requests(engine, &mut sessions);
        if concurrency == 8 {
            assert!(
                sessions.iter().all(|s| {
                    let stats = s.dspark_stats();
                    stats.skipped > 0 && stats.steps == 0
                }),
                "known unprofitable cycles skip without paying for a probe"
            );
        }
        for (s, snapshot) in sessions.iter_mut().zip(&snapshots) {
            s.restore_snapshot(engine, snapshot).unwrap();
        }
        assert!(
            continue_requests(engine, &mut sessions) == expected,
            "snapshot retains the partial concurrent cost window and exact backoff continuation"
        );
        let before = sessions[0].dspark_stats();
        dspark_step(engine, &mut sessions[0], 8, 7);
        let after = sessions[0].dspark_stats();
        assert!(
            after.steps == before.steps + 1 && after.skipped == before.skipped,
            "returning to C1 immediately resumes drafting after concurrent backoff"
        );
        println!(
            "DSpark concurrent controller snapshot C{concurrency}: exact window/backoff continuation"
        );
    }
}

fn dspark_changing_membership(engine: &mut Engine) {
    let mut run = || {
        // Shared scratch grows while older sessions stay live; the repeat can
        // reuse the largest workspace.
        let mut sessions: Vec<Session> = (0..4)
            .map(|i| {
                let mut s = session(engine, 512 + 256 * i as u32);
                let mut prompt = tokenize(engine, TRAJECTORY_PROMPT);
                while prompt.len() < 120 + i {
                    prompt.push(PINNED_TRAJECTORY[prompt.len() % 128]);
                }
                s.sync(engine, &prompt).unwrap();
                s
            })
            .collect();
        let mut observations: Vec<Observation> = Vec::new();
        for (cycle, width) in [1, 2, 4, 3, 1, 4, 2, 4].into_iter().enumerate() {
            let positions: Vec<usize> = sessions.iter().map(Session::position).collect();
            let order: Vec<usize> = (0..width).map(|slot| (slot + cycle) % 4).collect();
            // A one-token member must not force its eligible peers to draft
            // serially.
            let members = pick(&mut sessions, &order)
                .into_iter()
                .enumerate()
                .map(|(slot, s)| (s, if width > 2 && slot == 0 { 1 } else { 4 }))
                .collect();
            let emitted_in_order = dspark_batch(engine, members);
            let mut emitted = vec![Vec::new(); 4];
            for (&index, tokens) in order.iter().zip(emitted_in_order) {
                emitted[index] = tokens;
            }
            for (i, (s, tokens)) in sessions.iter().zip(emitted).enumerate() {
                assert_eq!(
                    s.position(),
                    positions[i] + tokens.len(),
                    "changing membership advances only the selected sessions"
                );
                observations.push((tokens, logits(s), s.dspark_stats(), s.position()));
            }
        }
        observations
    };
    let first = run();
    let repeat = run();
    if let Some(i) = (0..first.len()).find(|&i| first[i] != repeat[i]) {
        eprintln!(
            "Changing membership mismatch cycle={} member={} tokens_equal={} logits_equal={} stats_equal={} positions={}/{}",
            i / 4,
            i % 4,
            u8::from(first[i].0 == repeat[i].0),
            u8::from(first[i].1 == repeat[i].1),
            u8::from(first[i].2 == repeat[i].2),
            first[i].3,
            repeat[i].3
        );
    }
    assert!(
        first == repeat,
        "changing concurrency repeats exact tokens, logits, and state"
    );
    println!("DSpark changing membership C1/C2/C4/C3: exact repeated continuation");
}

fn dspark_reproducibility(engine: &mut Engine) {
    const PROMPTS: [&str; 4] = [
        "Continue the pattern: red, blue, blue, red, blue, blue, red,",
        "Return only JSON for a three-day study plan with topic and minutes.",
        "Explain why virtual memory is useful for a database engine.",
        "Write a concise C++20 fixed-capacity ring buffer implementation.",
    ];
    const CYCLES: usize = 6;
    for tail in [1u32, 3, 7] {
        let prompt = tokenize(engine, PROMPTS[0]);
        let mut configured = session(engine, 512);
        let mut legacy = session(engine, 512);
        configured.sync(engine, &prompt).unwrap();
        legacy.sync(engine, &prompt).unwrap();
        for _ in 0..4 {
            let before = configured.dspark_stats();
            let mut items = [DsparkItem {
                session: &mut configured,
                max_tokens: 16,
                max_draft_tokens: tail,
                sampler: None,
                stop_at_eos: false,
                emitted: Vec::new(),
            }];
            Session::dspark_step_batch(engine, &mut items).unwrap();
            let [item] = items;
            let emitted = item.emitted;
            let after = configured.dspark_stats();
            assert!(
                after.support_drafted - before.support_drafted <= u64::from(tail),
                "single-request draft limit is honored"
            );
            assert!(
                !emitted.is_empty() && emitted.len() <= tail as usize + 1,
                "single-request emitted prefix respects its limit"
            );
            let legacy_emitted = dspark_step(engine, &mut legacy, 16, tail);
            assert!(
                emitted == legacy_emitted && logits(&configured) == logits(&legacy),
                "C1 session and batch APIs retain identical tokens and logits"
            );
        }
        assert!(
            configured.dspark_stats().support_drafted > 0,
            "single-request limit check exercised proposals"
        );
    }
    for concurrency in [1usize, 2, 4, 6, 8] {
        let budget = |index: usize, cycle: usize| {
            if cycle == 0 {
                7
            } else {
                1 + (index + cycle) % 5
            }
        };
        let mut run = || {
            let mut sessions: Vec<Session> = (0..concurrency)
                .map(|i| {
                    let mut s = session(engine, 512);
                    let mut prompt = tokenize(engine, PROMPTS[i % PROMPTS.len()]);
                    assert!(!prompt.is_empty(), "DSpark repeat prompt tokenization");
                    if i >= PROMPTS.len() {
                        // Cross the ratio-128 compression boundary at
                        // different offsets.
                        let mut context = tokenize(engine, TRAJECTORY_PROMPT);
                        context.extend_from_slice(&PINNED_TRAJECTORY);
                        context.truncate(120 + i - prompt.len());
                        context.extend_from_slice(&prompt);
                        prompt = context;
                    }
                    s.sync(engine, &prompt).unwrap();
                    s
                })
                .collect();
            let mut observations: Vec<Observation> = Vec::new();
            for cycle in 0..CYCLES {
                // Rotated order and varied budgets: ragged rows,
                // rejection and rollback, and one-token tails.
                let order: Vec<usize> = (0..concurrency)
                    .map(|slot| (slot + cycle) % concurrency)
                    .collect();
                let members = pick(&mut sessions, &order)
                    .into_iter()
                    .zip(&order)
                    .map(|(s, &index)| (s, budget(index, cycle)))
                    .collect();
                let emitted_in_order = dspark_batch(engine, members);
                let mut emitted = vec![Vec::new(); concurrency];
                for (&index, tokens) in order.iter().zip(emitted_in_order) {
                    emitted[index] = tokens;
                }
                for (i, (s, tokens)) in sessions.iter().zip(emitted).enumerate() {
                    let row = logits(s);
                    assert!(
                        row.iter().all(|v| v.is_finite()),
                        "finite concurrent DSpark frontier logits"
                    );
                    assert!(!tokens.is_empty(), "each DSpark request makes progress");
                    assert!(
                        tokens.len() <= budget(i, cycle),
                        "DSpark respects request budget"
                    );
                    observations.push((tokens, row, s.dspark_stats(), s.position()));
                }
            }
            observations
        };
        let reference = run();
        let candidate = run();
        let mut fingerprint = Vec::new();
        for (tokens, row, stats, position) in &candidate {
            fingerprint.extend(common::token_bytes(tokens));
            fingerprint.extend(float_bytes(row));
            for value in [
                *position as u64,
                stats.support_drafted,
                stats.support_accepted,
                stats.verifier_rows,
            ] {
                fingerprint.extend_from_slice(&value.to_le_bytes());
            }
        }
        println!("DSpark fingerprint C{concurrency} {}", sha256(&fingerprint));
        assert_eq!(reference.len(), candidate.len(), "same observation count");
        for (i, (a, b)) in reference.iter().zip(&candidate).enumerate() {
            if a.0 != b.0 || a.1 != b.1 {
                eprintln!(
                    "DSpark repeat route mismatch C={concurrency} cycle={} request={} drafted={}/{} accepted={}/{} verifier={}/{} position={}/{}\ntokens: {:?}\ncandidate: {:?}",
                    i / concurrency,
                    i % concurrency,
                    a.2.support_drafted,
                    b.2.support_drafted,
                    a.2.support_accepted,
                    b.2.support_accepted,
                    a.2.verifier_rows,
                    b.2.verifier_rows,
                    a.3,
                    b.3,
                    a.0,
                    b.0
                );
            }
            assert!(a.0 == b.0, "DSpark repeat retains exact emitted tokens");
            assert!(a.1 == b.1, "DSpark repeat retains full frontier logits");
            assert_eq!(a.3, b.3, "DSpark repeat retains request position");
            assert_eq!(
                a.2, b.2,
                "DSpark repeat retains all speculative counters and support state"
            );
        }
        let last = &candidate[candidate.len() - concurrency..];
        let drafted: u64 = last.iter().map(|o| o.2.support_drafted).sum();
        if concurrency == 8 {
            assert!(
                drafted == 0 && last.iter().all(|o| o.2.steps == 0 && o.2.skipped > 0),
                "short-context C8 repeats without unprofitable probes"
            );
        } else {
            assert!(
                drafted > 0,
                "DSpark repeat comparison exercised DSpark proposals"
            );
        }
        println!(
            "DSpark repeat C{concurrency}: {} exact token/logit/state comparisons, drafted={drafted}",
            reference.len()
        );
    }
}

fn target_part(engine: &mut Engine) {
    session_round_trip(engine);
    batched_prefill(engine);
    conversational_prefill(engine);
    wide_prefill(engine);
    session_batch(engine);
    session_bounds(engine);
    // Last: optimized builds of both engines miss its top-1 and rank gates
    // with identical logits (`docs/models/deepseek-v4-flash/QUALITY.md`).
    pinned_trajectory(engine);
}

fn dspark_part(engine: &mut Engine) {
    indexer_boundary(engine, false);
    indexer_boundary(engine, true);
    dspark_reproducibility(engine);
    dspark_changing_membership(engine);
    concurrent_policy_snapshot(engine);
    dspark_scalar_quality(engine);
    dspark_prompt_seed(engine);
    dspark_snapshots(engine);
    session_bounds(engine);
}

