//! The QUALITY checks of DeepSeek V4 Flash on the Rust engine, ported from
//! `tests/models/deepseek_v4_flash/quality_test.cpp` with its thresholds.
//! The target part (`ds4.target`, no support model): a session with a
//! snapshot round trip, the pinned 128-token antirez/ds4 trajectory, batched
//! against sequential prefill (with conversational widths and a 2K prompt at
//! 4K and 262K capacity), batched decode of two to eight sessions with
//! changing membership and preflight rejections, and context bounds. The
//! DSpark part (`ds4.dspark`): DSpark C1 and AR C2 against AR across the
//! first sparse-indexer boundary, exact repeats at C1 to C8, changing
//! membership, concurrent controller snapshots, every DSpark frontier against
//! a scalar replay at C1 to C8 and depths to 16K, prompt seeding, exact
//! snapshot continuation to 16K, and context bounds. One test runs both, the
//! model loaded once per part (two loads must not overlap):
//! cargo test --profile gpu-test -p gufo-deepseek-v4-flash --features gpu,models \
//!   --test quality -- --ignored --nocapture
//!
//! `GUFO_DS4_QUALITY` = `target`, `dspark`, `dspark-replay`,
//! `indexer-boundary` or `wide-prefill` runs that part alone (the C++
//! `--dspark`, `--dspark-replay`, `--indexer-boundary`, `--wide-prefill`).
//! The Hugging Face token goldens are in `tests/chat_template.rs`.

